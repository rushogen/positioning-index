#!/usr/bin/env node
/**
 * Turn seed/companies.json into idempotent SQL.
 *
 *   node scripts/build-seed-sql.js > seed.sql
 *
 * Re-runnable: companies upsert on slug, targets upsert on (company, kind).
 * Existing crawl state (next_due_at, etag, content_hash) is preserved on
 * update, so re-seeding after adding a company does not reset the queue or
 * cause a stampede of refetches.
 */

import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

const q = (v) => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

/** Exported so scripts/demo.js can seed a local database without shelling out. */
export async function buildSeedSql() {
const seed = JSON.parse(await readFile(new URL('../seed/companies.json', import.meta.url), 'utf8'));
const now = new Date().toISOString().replace(/\.\d{3}Z$/, 'Z');

const out = [];
out.push('-- Generated by scripts/build-seed-sql.js. Do not edit by hand.');
out.push(`-- Source: seed/companies.json v${seed.version} (${seed.companies.length} companies)`);
out.push('');

for (const c of seed.companies) {
  out.push(
    `INSERT INTO companies (slug, name, homepage_url, pricing_url, segment, hq_country, added_at, active)\n` +
    `VALUES (${q(c.slug)}, ${q(c.name)}, ${q(c.homepage_url)}, ${q(c.pricing_url)}, ${q(c.segment)}, ${q(c.hq_country)}, ${q(now)}, 1)\n` +
    `ON CONFLICT(slug) DO UPDATE SET name=excluded.name, homepage_url=excluded.homepage_url,\n` +
    `  pricing_url=excluded.pricing_url, segment=excluded.segment, hq_country=excluded.hq_country, active=1;`
  );
}
out.push('');

// Stagger the first due time so the very first sweep does not fire every target
// at once. Five minutes apart matches the tick cadence exactly.
let slot = 0;
for (const c of seed.companies) {
  for (const [kind, url] of [['home', c.homepage_url], ['pricing', c.pricing_url]]) {
    if (!url) continue;
    const host = new URL(url).hostname;
    const due = new Date(Date.now() + slot * 5 * 60_000).toISOString().replace(/\.\d{3}Z$/, 'Z');
    slot++;
    out.push(
      `INSERT INTO targets (company_id, kind, url, host, next_due_at, enabled)\n` +
      `SELECT id, ${q(kind)}, ${q(url)}, ${q(host)}, ${q(due)}, 1 FROM companies WHERE slug = ${q(c.slug)}\n` +
      `ON CONFLICT(company_id, kind) DO UPDATE SET url=excluded.url, host=excluded.host, enabled=1;`
    );
  }
}

out.push('');
out.push(`-- ${slot} crawl targets. At one tick every 5 minutes that is a full sweep every ${(slot * 5 / 60).toFixed(1)} hours.`);
  return out.join('\n');
}

// CLI: node scripts/build-seed-sql.js > seed.sql
//
// pathToFileURL rather than `file://${process.argv[1]}`: import.meta.url is
// percent-encoded, so the naive comparison silently fails for any checkout
// whose path contains a space, and the script prints nothing.
if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  console.log(await buildSeedSql());
}
